// Builds docs/GENERATOR_INDEX.md: one section per generator/injector file listing
// what it writes or edits and the terms inside its template strings (Elixir modules,
// config keys, deps, routes). graphify's AST pass cannot see inside template literals,
// so this index is how `graphify section "<file or term>"` finds generated code.
//   node scripts/generator_index.mjs
import { readFileSync, readdirSync, statSync, writeFileSync, mkdirSync } from "fs";
import { join, relative } from "path";

const ROOTS = ["generators", "injectors", "composite"];
const OUT = join("docs", "GENERATOR_INDEX.md");

const walk = (dir) =>
  readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    return statSync(path).isDirectory() ? walk(path) : path.endsWith(".ts") ? [path] : [];
  });

const uniq = (items) => [...new Set(items)].sort();
const matches = (text, regex, group = 1) => uniq([...text.matchAll(regex)].map((m) => m[group]));

// Text inside backtick template literals: where the generated Elixir/TS lives
const templates = (source) => matches(source, /`([\s\S]*?)`/g).join("\n");

const facts = (source) => {
  const body = templates(source);
  return {
    exports: matches(source, /export\s*\{([^}]*)\}/g).flatMap((list) => list.split(",").map((s) => s.trim()).filter(Boolean)),
    writes: matches(source, /filename:\s*[`"']([^`"']+)[`"']|filename\s*=\s*[`"']([^`"']+)[`"']/g, 0).map((m) =>
      m.replace(/^filename\s*[:=]\s*[`"']|[`"']$/g, "")
    ),
    edits: matches(source, /join\(\s*UmbrellaDir[^)]*?,\s*["'`]([^"'`]+)["'`]/g),
    modules: matches(body, /\b((?:[A-Z][A-Za-z0-9]*\.)+[A-Z][A-Za-z0-9]*)\b/g).filter((m) => !m.includes("${")),
    config: matches(body, /config\s+(:[a-z_${}A-Za-z]+(?:,\s*[:A-Z][\w.${}]*)?)/g),
    deps: matches(body, /\{:([a-z_]+),\s*"/g),
    routes: matches(body, /\b(?:get|post|put|patch|delete|forward)\(?\s*"(\/[^"]*)"/g),
  };
};

const line = (label, items) => (items.length ? `- **${label}:** ${items.map((i) => `\`${i}\``).join(", ")}` : "");

const section = (path) => {
  const f = facts(readFileSync(path, "utf8"));
  const lines = [
    line("Exports", f.exports),
    line("Writes", f.writes),
    line("Edits", f.edits),
    line("Elixir modules", f.modules),
    line("Config", f.config),
    line("Deps", f.deps),
    line("Routes", f.routes),
  ].filter(Boolean);
  return `## ${relative(".", path).replace(/\\/g, "/")}\n\n${lines.join("\n") || "- (no template content)"}\n`;
};

const files = ROOTS.flatMap(walk).sort();
const header = `# Generator index

Generated by \`node scripts/generator_index.mjs\`; do not edit by hand.
One section per generator, injector and composite file, listing the files it writes or
edits and the terms inside its template strings. Use \`graphify section "<path>"\`, or
search this file, to find which generator produces a given Elixir module, config key,
dep or route.

`;

mkdirSync("docs", { recursive: true });
writeFileSync(OUT, header + files.map(section).join("\n"));
console.log(`Wrote ${OUT} (${files.length} files)`);
