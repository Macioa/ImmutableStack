import { AppData } from "../../readers/get_app_data";
import { join } from "../../utils/path";
import { ApiAppData } from "../add_api";
import { generateFile } from "../index";

const FILENAME = ".gitignore";

const mixIgnore = `# The directory Mix will write compiled artifacts to.
/_build/

# If you run "mix test --cover", coverage assets end up here.
/cover/

# The directory Mix downloads your dependencies sources to.
/deps/

# Where 3rd-party dependencies like ExDoc output generated docs.
/doc/

# Ignore .fetch files in case you like to edit your project deps locally.
/.fetch

# If the VM crashes, it generates a dump, let's ignore it too.
erl_crash.dump

# Also ignore archive artifacts (built via "mix archive.build").
*.ez

# Temporary files, for example, from tests.
/tmp/
`;

const libIgnore = (appName: string) => `${mixIgnore}
# TypeScript/Node.js dependencies
lib/typescript/node_modules

# Ignore package tarball (built via "mix hex.build").
${appName}-*.tar`;

const endpointIgnore = (appName: string) => `${mixIgnore}
# Ignore package tarball (built via "mix hex.build").
${appName}-*.tar

# Static assets (generated by build process)
priv/static/*/`;

const gen_gitignore_phoenix = async ({ LibDir, WebDir, AppNameSnake }: AppData) =>
  Promise.all([
    generateFile(
      { filename: FILENAME, dir: LibDir, content: libIgnore(AppNameSnake) },
      "gen_gitignore_phoenix_lib"
    ),
    generateFile(
      { filename: FILENAME, dir: WebDir, content: endpointIgnore(`${AppNameSnake}_web`) },
      "gen_gitignore_phoenix_web"
    ),
  ]);

const gen_gitignore_api = async ({ AppDir, AppNameSnake, ApiNameSnake }: ApiAppData) => {
  const appName = `${AppNameSnake}_${ApiNameSnake}`;
  return generateFile(
    { filename: FILENAME, dir: join(AppDir || "", appName), content: endpointIgnore(appName) },
    "gen_gitignore_api"
  );
};

export { gen_gitignore_api, gen_gitignore_phoenix };
